/**
 * mihomo config for the subscription case.
 *
 * The subscription is pulled by mihomo itself (`proxy-providers`), so the
 * crawler never parses proxy protocols and reuses the engine's own health
 * checks. The selector group is the only knob rotation touches.
 */

import {
  CONTAINER_WORKER_PORT_BASE,
  MAX_WORKERS,
  workerGroup
} from "./constants"

export interface MihomoInput {
  readonly subscriptionUrl: string
  /** Mixed HTTP/SOCKS port inside the container. */
  readonly port: number
  readonly controllerPort: number
  readonly secret: string
  readonly group: string
  /** Per-worker listeners and groups; defaults to all available slots. */
  readonly workers?: number
}

export const renderMihomoConfig = (input: MihomoInput): string => {
  const workers = Math.max(1, Math.min(input.workers ?? MAX_WORKERS, MAX_WORKERS))
  const groups = Array.from({ length: workers }, (_, index) => workerGroup(index))

  return [
    "# Generated by `otbor proxy up`; rewritten on every start. Do not edit.",
    "# allow-lan is required inside the container: Docker publishes the port",
    "# to host loopback only, so the listener itself must accept the bridge.",
    `mixed-port: ${input.port}`,
    "allow-lan: true",
    'bind-address: "*"',
    "mode: rule",
    'log-level: "warning"',
    "ipv6: false",
    "unified-delay: true",
    `external-controller: ${quote(`0.0.0.0:${input.controllerPort}`)}`,
    `secret: ${quote(input.secret)}`,
    "profile:",
    "  store-selected: true",
    "proxy-providers:",
    "  otbor-sub:",
    "    type: http",
    `    url: ${quote(input.subscriptionUrl)}`,
    "    interval: 3600",
    "    path: ./providers/otbor-sub.yaml",
    "    health-check:",
    "      enable: true",
    `      url: ${quote("https://www.gstatic.com/generate_204")}`,
    "      interval: 300",
    "proxy-groups:",
    `  - name: ${quote(input.group)}`,
    "    type: select",
    "    use:",
    "      - otbor-sub",
    ...groups.flatMap((name) => [
      `  - name: ${quote(name)}`,
      "    type: select",
      "    use:",
      "      - otbor-sub"
    ]),
    "listeners:",
    ...groups.flatMap((name, index) => [
      `  - name: ${quote(name)}`,
      "    type: mixed",
      `    port: ${CONTAINER_WORKER_PORT_BASE + index + 1}`,
      `    listen: ${quote("0.0.0.0")}`,
      `    proxy: ${quote(name)}`
    ]),
    "rules:",
    `  - MATCH,${input.group}`,
    ""
  ].join("\n")
}

/** JSON string syntax is valid YAML for the scalars used here. */
const quote = (value: string): string => JSON.stringify(value)

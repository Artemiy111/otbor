/**
 * hh id пользователя, вошедшего на странице, из начального состояния hh.
 *
 * Свой `hhid` hh пишет строкой (`"hhid":"197366351"`), а чужие (менеджер
 * работодателя в `employerManager`, он есть на странице отклика) числом. Поэтому
 * берётся только строковая форма, как и в `otbor hh login`: иначе первым
 * совпадением оказывается работодатель, аккаунт не опознаётся и письмо не
 * подставляется.
 */
const HHID_RE = /"hhid"\s*:\s*"(\d+)"/

export const hhidOfText = (text: string): string | null => HHID_RE.exec(text)?.[1] ?? null

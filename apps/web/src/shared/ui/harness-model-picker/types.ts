/** Харнес, доступный в рейле выбора. */
export interface HarnessEntry {
  /** Идентификатор провайдера: opencode, codex, openai. */
  id: string;
  /** Подпись для рейла и подсказки. */
  name: string;
  /** Почему харнес недоступен; без значения харнес рабочий. */
  error?: string | null;
}

/** Модель, которую отдаёт список моделей провайдера. */
export interface HarnessModel {
  /** Идентификатор модели для провайдера. */
  id: string;
  /** Харнес-вкладка, к которой относится модель. */
  harness: string;
  /**
   * Вид модели внутри харнеса: подписка, API-кредиты, отдельный аккаунт.
   * Показывается строкой под названием, чтобы `opencode` и `opencode-go`
   * не выглядели одной и той же моделью.
   */
  variant?: string;
  /** Человекочитаемое имя без префикса провайдера. */
  label: string;
  /** Допустимые варианты усилия; пусто: выбора нет. */
  efforts: string[];
  /** Усилие по умолчанию от провайдера. */
  defaultEffort?: string;
}

/** Псевдовкладка избранного в рейле. */
export const FAVORITES_TAB = "__favorites";
